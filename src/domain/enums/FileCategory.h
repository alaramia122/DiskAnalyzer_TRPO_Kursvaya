#pragma once

#include <cstddef>
#include <cstdint>

namespace domain
{
    /**
     * @brief Категория файла для статистики и визуализации.
     *
     * Значения используются как индексы массивов категориальной статистики.
     * При изменении набора категорий необходимо синхронно проверить
     * FileCategoryCount и таблицу расширений FileClassifier.
     */
    enum class FileCategory : std::uint8_t
    {
        Unknown,     ///< Категория не определена или не классифицирована
        Documents,   ///< Текстовые документы, офисные форматы и PDF
        Images,      ///< Растровые и векторные изображения
        Video,       ///< Видеофайлы
        Audio,       ///< Аудиофайлы
        Archives,    ///< Архивы и сжатые файлы
        Executables, ///< Исполняемые файлы и установочные пакеты
        SourceCode,  ///< Исходный код и связанные текстовые форматы
        System,      ///< Системные библиотеки и драйверы
        Other        ///< Расширение не найдено в таблице классификатора
    };

    // Число категорий должно соответствовать количеству элементов FileCategory.
    constexpr std::size_t FileCategoryCount = 10;
}
