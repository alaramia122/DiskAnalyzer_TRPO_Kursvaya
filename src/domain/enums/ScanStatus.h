#pragma once

#include <cstdint>

namespace domain
{
    /**
     * @brief Состояние процесса сканирования файловой системы.
     *
     * ScanStatus возвращается из синхронного конвейера и передаётся наружу
     * контроллером через сигнал analysisFinished. Idle и Running описывают
     * общие состояния задачи, но не являются итогом успешно завершённого обхода.
     */
    enum class ScanStatus : std::uint8_t
    {
        Idle,       ///< Анализ не запущен
        Running,    ///< Анализ выполняется
        Completed,  ///< Сканирование и предусмотренная агрегация завершены
        Cancelled,  ///< Получен запрос на отмену
        Failed      ///< Операцию не удалось завершить
    };
}
